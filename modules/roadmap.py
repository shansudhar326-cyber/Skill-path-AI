"""
Module: Personalized Learning Roadmap & Adaptive Rescue Center
Visualizes weekly milestones, course links, YouTube tutorials, documentation,
and dynamically hosts remedial Rescue Modules generated by the Learning Rescue Agent.
"""

import streamlit as st
from SkillPath_AI.database.db import (
    get_student_by_id, get_roadmap, update_roadmap_status,
    get_active_rescue_plans, resolve_rescue_plan
)

def render_roadmap_module(student_id: int):
    st.markdown("""
    <div style="margin-bottom: 20px;">
        <h2 style="font-weight: 800; color: #1e293b; margin:0;">🗺️ Personalized Learning Roadmap</h2>
        <p style="color: #64748b; font-size: 14px; margin-top: 4px;">
            A customized, adaptive curriculum updated dynamically by your Career Digital Twin based on assessment feedback and goals.
        </p>
    </div>
    """, unsafe_allow_html=True)

    student = get_student_by_id(student_id)
    if not student:
        st.error("Student profile not found.")
        return

    # 1. Active Rescue Plans Section
    active_rescues = get_active_rescue_plans(student_id)
    if active_rescues:
        for r in active_rescues:
            st.markdown(f"""
            <div class="rescue-banner">
                <div class="rescue-title">🚨 Active Learning Rescue Sprint: {r['weak_topic']}</div>
                <p class="rescue-text">
                    <strong>Trigger Score:</strong> {r['score_trigger']}% • 
                    <strong>Status:</strong> Active Intervention
                </p>
                <div style="background:rgba(255,255,255,0.7); border-radius:8px; padding:12px; margin:10px 0;">
                    <strong style="color:#92400e;">💡 Simplified Mental Model:</strong>
                    <p style="color:#78350f; font-size:13px; margin:4px 0 0 0; line-height:1.5;">{r['explanation_simple']}</p>
                </div>
            </div>
            """, unsafe_allow_html=True)

            with st.expander(f"📚 View Recommended Tutorials & Practice Questions for {r['weak_topic']}", expanded=True):
                st.markdown("#### 🎥 Remediation Video Tutorials & Guides")
                for tut in r.get("tutorials", []):
                    st.markdown(f"""
                    - **[{tut.get('title')}]({tut.get('url')})** ({tut.get('platform')}, {tut.get('duration', 'N/A')})
                    """)

                st.markdown("#### ✍️ Scaffolded Practice Exercises")
                for ex in r.get("practice_questions", []):
                    st.markdown(f"""
                    <div style="background:#f8fafc; border:1px solid #e2e8f0; border-radius:6px; padding:10px; margin-bottom:8px;">
                        <strong style="color:#4f46e5; font-size:13px;">{ex.get('level', 'Exercise')}</strong>: {ex.get('task')}
                        <div style="font-size:11px; color:#64748b; margin-top:4px;">💡 <em>Hint: {ex.get('hint')}</em></div>
                    </div>
                    """, unsafe_allow_html=True)

                if st.button(f"✅ Mark {r['weak_topic']} Remediated & Clear Rescue", key=f"resolve_rescue_{r['id']}"):
                    resolve_rescue_plan(r['id'], student_id)
                    st.success("Rescue plan resolved! Downstream roadmap unlocked.")
                    st.rerun()

    # 2. Roadmap Milestones
    roadmap = get_roadmap(student_id)
    if not roadmap:
        st.info("No learning roadmap generated yet.")
        return

    # Progress Bar across weeks
    completed_count = sum(1 for item in roadmap if item["status"] == "Completed")
    total_count = len(roadmap)
    progress_pct = int((completed_count / total_count) * 100) if total_count > 0 else 0

    st.markdown(f"""
    <div class="sp-card" style="margin-bottom:20px;">
        <div style="display:flex; justify-content:space-between; margin-bottom:8px;">
            <strong style="color:#1e293b;">Overall Curriculum Progress</strong>
            <span style="color:#4f46e5; font-weight:700;">{completed_count} of {total_count} Modules Completed ({progress_pct}%)</span>
        </div>
        <div style="background:#e2e8f0; border-radius:9999px; height:10px; overflow:hidden;">
            <div style="background:#4f46e5; width:{progress_pct}%; height:100%;"></div>
        </div>
    </div>
    """, unsafe_allow_html=True)

    for item in roadmap:
        status = item["status"]
        status_badge = {
            "Completed": "badge-success",
            "In Progress": "badge-primary",
            "Rescue": "badge-warning",
            "Pending": "badge-agent"
        }.get(status, "badge-agent")

        yt_search_url = f"https://www.youtube.com/results?search_query={item.get('youtube_query', item['topic']).replace(' ', '+')}"

        st.markdown(f"""
        <div class="roadmap-item {status.lower().replace(' ', '-')}">
            <div style="display:flex; justify-content:space-between; align-items:center;">
                <div>
                    <span style="font-size:12px; font-weight:700; color:#6366f1;">WEEK {item['week_number']} • TARGET: {item['skill_target']}</span>
                    <h3 style="margin:2px 0 6px 0; font-size:17px; color:#1e293b;">{item['topic']}</h3>
                </div>
                <span class="badge {status_badge}">{status}</span>
            </div>
            <p style="color:#475569; font-size:13px; line-height:1.5; margin-bottom:12px;">{item['description']}</p>
            
            <div style="display:flex; flex-wrap:wrap; gap:16px; font-size:12px; margin-bottom:12px; padding:10px; background:#f8fafc; border-radius:8px;">
                <div>🎓 <strong>Course:</strong> <a href="{item.get('course_url', '#')}" target="_blank">{item.get('course_title', 'Curated Track')}</a></div>
                <div>📺 <strong>Tutorials:</strong> <a href="{yt_search_url}" target="_blank">Search YouTube</a></div>
                <div>📖 <strong>Docs:</strong> <a href="{item.get('doc_url', '#')}" target="_blank">Documentation</a></div>
            </div>

            <div style="background:#f1f5f9; padding:8px 12px; border-radius:6px; font-size:12px; color:#1e293b; margin-bottom:12px;">
                <strong>🛠️ Practical Task:</strong> {item.get('practical_task', 'Build milestone project')}
            </div>
        </div>
        """, unsafe_allow_html=True)

        col_st1, col_st2, col_st3 = st.columns([1, 1, 3])
        with col_st1:
            if status != "Completed" and st.button("Mark Completed", key=f"comp_{item['id']}"):
                update_roadmap_status(item["id"], student_id, "Completed")
                st.rerun()
        with col_st2:
            if status != "In Progress" and status != "Completed" and st.button("Start Module", key=f"prog_{item['id']}"):
                update_roadmap_status(item["id"], student_id, "In Progress")
                st.rerun()
        with col_st3:
            if status == "Completed" and st.button("Reopen Module", key=f"reopen_{item['id']}"):
                update_roadmap_status(item["id"], student_id, "In Progress")
                st.rerun()

        st.markdown("<div style='height:8px;'></div>", unsafe_allow_html=True)
